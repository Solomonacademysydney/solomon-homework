'use strict';
const fs = require('fs');
const 교 = fs.readFileSync('E:/aa0/hp/ts/index.html', 'utf8');

function 떼기(a, b) {
  const i = 교.indexOf(a), j = 교.indexOf(b, i + 10);
  if (i < 0 || j < 0) throw new Error('못 찾음: ' + a);
  return 교.slice(i, j);
}

/**
 * 「오늘」을 갈아 끼워 만든다 — 날짜에 기대는 코드는 날짜를 줘야 잰다.
 *
 * ⛔ 떼어 낸 글 안에 **파일 자신의 `시드니지금`** 이 들어 있다. 함수 선언은 내가 넣은
 *    매개변수를 **덮는다.** 그래서 그 한 토막을 **도려내고** 내 것을 쓰게 한다.
 *    (안 도려내면 파일 것이 돌면서 「시드니 is not defined」로 터진다 — 실측.)
 */
function 세상(오늘) {
  let 소스 = 떼기('const 요일말 = ', 'function 칸이름');
  소스 = 소스.replace(/function 시드니지금\(\)\s*\{[\s\S]*?\n\}/, '');
  return new Function('시드니지금', 소스 + '\n; return {아이주차, 며칠뒤, 이번주차, 앞주차};')(
    () => new Date(오늘.getFullYear(), 오늘.getMonth(), 오늘.getDate()));
}

let 통과 = 0, 실패 = 0;
function 재기(이름, 얻은, 바란) {
  const a = JSON.stringify(얻은), b = JSON.stringify(바란);
  if (a === b) { 통과++; console.log('  ✅ ' + 이름 + '  → ' + a); }
  else { 실패++; console.log('  ⛔ ' + 이름 + '\n       얻은 ' + a + '\n       바란 ' + b); }
}
function 주차만(r) { return r ? { 배정: r.배정, 분석: r.분석 } : null; }

