// 승인 결과를 화면이 **그대로** 보이는지 잰다.
//
// ⛔ 재는 것 = 「막힌 까닭을 감추지 않는가」. 성공만 잘 보이고 실패가 뭉개지면,
//    원장님이 안 나간 숙제를 나간 줄 아신다. 그게 제일 나쁜 결과다.
// ⛔ 답 꼴은 **서버가 실제로 준 것**을 쓴다(오늘 라이브에서 받은 것).

const fs = require('fs');
const html = fs.readFileSync('E:/aa0/hp/ts/index.html', 'utf8');

function 떼기(a, b) {
  const i = html.indexOf(a), j = html.indexOf(b, i + 10);
  if (i < 0 || j < 0) throw new Error('못 찾음: ' + a);
  return html.slice(i, j);
}
const 소스 = 떼기('function 글(s){', 'function 시각말(')
           + 떼기('function 승인결과그리기(d){', '// ─────────────────── 교사 리포트');
const F = new Function(소스 + '\n; return {글, 승인결과그리기};')();

let 통과 = 0, 실패 = 0;
function 재기(이름, 참, 덧) {
  if (참) { 통과++; console.log('  ✅ ' + 이름); }
  else { 실패++; console.log('  ⛔ ' + 이름 + (덧 ? '\n       ' + 덧 : '')); }
}

console.log('── 됐을 때');
let h = F.승인결과그리기({ 결과: 'ok', 칸: 'AU_y4_2026_m09_w4', 서버해시: 'abc', 공개상태: '비공개(수학 대기)' });
재기('올렸다고 말한다', h.includes('올렸습니다'));
재기('칸을 보인다', h.includes('AU_y4_2026_m09_w4'));
재기('⭐ 아직 아이에게 안 보인다고 밝힌다', h.includes('공개') && h.includes('따로'));
재기('녹색 띠다', h.includes('알림 녹색'));

h = F.승인결과그리기({ 결과: 'ok', 이미: true, 칸: 'K', 공개상태: '비공개' });
재기('두 번 눌렀으면 「이미」라고 말한다', h.includes('이미 올라가 있었습니다'));

console.log('\n── 막혔을 때 (오늘 라이브에서 실제로 받은 답들)');
h = F.승인결과그리기({ 결과: '막힘', 까닭: '화면이 보낸 해시가 초안 본문과 다릅니다.', 서버해시: '2f86a1' });
재기('까닭을 그대로 보인다', h.includes('해시가 초안 본문과 다릅니다'));
재기('빨간 띠다', h.includes('알림 빨강'));

h = F.승인결과그리기({ 결과: '막힘', 까닭: '초안 판이 다릅니다 — 화면 99 · 서버 1' });
재기('판 어긋남도 그대로', h.includes('화면 99 · 서버 1'));

h = F.승인결과그리기({ 결과: '막힘', 까닭: '초안 검사에서 걸렸습니다.',
                 걸린것: ['3번 문항에 지문이 없습니다', '5번 문항의 정답 E 가 보기 4개 밖입니다'] });
재기('걸린 것을 하나하나 보인다',
     h.includes('지문이 없습니다') && h.includes('보기 4개 밖'));

h = F.승인결과그리기({ 결과: '막힘', 까닭: '검수가 취소된 문항이 들어 있습니다.',
                 막힌문항: ['ts-a-1', 'ts-b-2'], 자격판기준: '2026-09-19T17:42' });
재기('막힌 문항 번호를 보인다', h.includes('ts-a-1') && h.includes('ts-b-2'));
재기('⭐ 자격판이 언제 기준인지 보인다 (PC 가 꺼져 있었을 수 있다)',
     h.includes('2026-09-19T17:42'));

h = F.승인결과그리기({ 결과: '막힘', 까닭: '이 칸을 2명이 봅니다: Minah, Keira05',
                 받는이: ['Minah', 'Keira05'] });
재기('누가 보게 되는지 이름을 보인다', h.includes('Minah') && h.includes('Keira05'));

console.log('\n── ⛔ 확인 대기 — 「됐다」고 하면 안 된다');
h = F.승인결과그리기({ 결과: '확인대기', 칸: 'K',
                 까닭: '저장이 끝났는지 확인하지 못했습니다. 다시 눌러 주십시오.' });
재기('「올렸습니다」라고 하지 않는다', !h.includes('올렸습니다'));
재기('녹색으로 보이지 않는다', !h.includes('알림 녹색'));
재기('다시 누르라고 말한다', h.includes('한 번 더'));
재기('⭐ 두 번 써지지 않는다고 안심시킨다', h.includes('두 번 써지지 않습니다'));
재기('잠금을 그대로 뒀다고 밝힌다', h.includes('잠금은 그대로'));

console.log('\n── 아이 글이 그대로 HTML 이 되면 안 된다');
h = F.승인결과그리기({ 결과: '막힘', 까닭: '<img src=x onerror=alert(1)>',
                 걸린것: ['<b>가</b>'], 막힌문항: ["ts-x'\"<y>"] });
재기('까닭의 꺾쇠가 글자로 나간다', h.includes('&lt;img') && !h.includes('<img src=x'));
재기('걸린 것의 꺾쇠도', h.includes('&lt;b&gt;'));
재기('문항 번호의 따옴표도', !h.includes("ts-x'\"<y>"));

console.log('\n── 까닭을 못 받았을 때도 빈 칸으로 두지 않는다');
h = F.승인결과그리기({ 결과: '막힘' });
재기('「까닭을 못 받았습니다」라고 적는다', h.includes('까닭을 못 받았습니다'));

console.log('\n셈 — 통과 ' + 통과 + ' · 실패 ' + 실패);
process.exit(실패 ? 1 : 0);
